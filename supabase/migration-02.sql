-- 이미 있는 테이블에 컬럼만 더하는 것이라 기존 데이터는 그대로 남는다.
-- (schema.sql 을 다시 실행할 필요 없다)


-- ===========================================================================
-- 1. ended_on — 해지한 날
-- ===========================================================================
-- 지금까지는 '해지하기'를 누르면 구독 행을 지웠고, 딸린 이용 기록도
-- on delete cascade 로 같이 사라졌다. 몇 달치 기록이 한 번에 없어지는 셈이다.
--
-- 받은 피드백: "해지했을 때 이전 기록은 남고 이후로만 기록이 안 되면 좋겠다."
-- 맞는 말이다. 지운 게 아니라 '그만 쓰기 시작한 날'을 적어 두는 쪽이
-- 사실에 가깝고, 나중에 다시 가입할지 판단할 근거도 남는다.
--
-- null 이면 아직 쓰고 있는 구독이다.

alter table public.subscriptions
  add column if not exists ended_on date;


-- ===========================================================================
-- 2. custom_name / custom_category — 목록에 없는 서비스
-- ===========================================================================
-- 서비스 목록(src/data/services.ts)에 없는 걸 쓰는 사람은 아예 등록을 못 했다.
-- 직접 입력한 경우 이름과 카테고리를 구독 행에 같이 적어 둔다.
--
-- 왜 services 테이블에 넣지 않고 여기 두는가:
-- 직접 추가한 서비스는 그 사람에게만 해당한다. 공용 목록에 넣으면
-- 남의 화면에도 나오고, 오타나 중복이 그대로 쌓인다.

alter table public.subscriptions
  add column if not exists custom_name text;

alter table public.subscriptions
  add column if not exists custom_category text;


